// The Caddyfile, generated from services.yml. Caddy watches the file and reloads when it changes.
import { writeFileSync, readFileSync, renameSync } from 'node:fs';
import type { Redirect, Service } from './settings.js';

/** Headers the portal sets for the services: always removed from incoming requests, so they can't be forged. */
export const AUTH_HEADERS = ['X-Auth-Request-Email', 'X-Auth-Request-User'];

export type CaddyOptions = { labDomain: string; portalUpstream: string; acmeEmail: string; localCerts?: boolean };

function proxy(service: Service, indent: string): string {
  if (!service.timeout) return `${indent}reverse_proxy ${service.upstream}`;
  return [
    `${indent}reverse_proxy ${service.upstream} {`,
    `${indent}\ttransport http {`,
    `${indent}\t\tread_timeout ${service.timeout}`,
    `${indent}\t\twrite_timeout ${service.timeout}`,
    `${indent}\t}`,
    `${indent}}`,
  ].join('\n');
}

export function renderCaddyfile(services: Service[], o: CaddyOptions, redirects: Redirect[] = []): string {
  const out: string[] = [];
  out.push('# Generated by the lab portal from services.yml. Do not edit: it is overwritten.');
  const global = [o.acmeEmail && `\temail ${o.acmeEmail}`, o.localCerts && '\tlocal_certs'].filter(Boolean) as string[];
  if (global.length) out.push('{', ...global, '}');
  out.push('');
  out.push(`# The portal: login, the overview of the services, membership`);
  out.push(`${o.labDomain} {`);
  out.push(`\t# The authorization endpoint is only for Caddy itself`);
  out.push(`\t@auth path /auth /auth/*`);
  out.push(`\trespond @auth 404`);
  out.push(`\treverse_proxy ${o.portalUpstream}`);
  out.push(`}`);
  for (const s of services) {
    out.push('');
    out.push(`# ${s.name}: ${s.access === 'public' ? 'no lab login' : `lab login (${s.access}, second factor ${s.mfa})`}`);
    out.push(`${s.host} {`);
    for (const h of AUTH_HEADERS) out.push(`\trequest_header -${h}`);
    if (s.maxUpload) out.push(`\trequest_body {`, `\t\tmax_size ${s.maxUpload}`, `\t}`);
    if (s.access === 'public') {
      out.push(proxy(s, '\t'));
    } else {
      if (s.apiBypass.length) {
        out.push(`\t# API requests with their own key (an Authorization header): the service checks the key itself`);
        out.push(`\t@api {`, `\t\tpath ${s.apiBypass.join(' ')}`, `\t\theader Authorization *`, `\t}`);
        out.push(`\thandle @api {`, proxy(s, '\t\t'), `\t}`);
      }
      out.push(`\thandle {`);
      out.push(`\t\tforward_auth ${o.portalUpstream} {`);
      out.push(`\t\t\turi /auth`);
      out.push(`\t\t\tcopy_headers ${AUTH_HEADERS.join(' ')}`);
      out.push(`\t\t}`);
      out.push(proxy(s, '\t\t'));
      out.push(`\t}`);
    }
    out.push(`}`);
  }
  for (const r of redirects) {
    out.push('', `# Moved`, `${r.from} {`, `\tredir ${r.to}{uri} permanent`, `}`);
  }
  return out.join('\n') + '\n';
}

/** Writes the file only when it changed (so Caddy only reloads when needed), atomically. */
export function writeCaddyfile(file: string, content: string): boolean {
  try {
    if (readFileSync(file, 'utf8') === content) return false;
  } catch {
    // no file yet
  }
  writeFileSync(`${file}.tmp`, content);
  renameSync(`${file}.tmp`, file);
  return true;
}
